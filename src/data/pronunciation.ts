/** Names spelled differently in American English. */
const US_SPELLING: Record<string, string> = { Al: 'Aluminum', Cs: 'Cesium' }

export function ipa(symbol: string, accent: Accent): string {
  const p = IPA[symbol]
  if (!p) return ''
  return accent === 'us' ? (p[1] ?? p[0]) : p[0]
}

/** English name as spelled in that accent (Aluminium / Aluminum). */
export function englishName(symbol: string, ukName: string, accent: Accent): string {
  return accent === 'us' ? (US_SPELLING[symbol] ?? ukName) : ukName
}

